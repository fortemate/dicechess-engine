def make_model(
    graph_name: str = "synthetic-kcp13-value",
    input_name: str = INPUT_NAME,
    output_name: str = OUTPUT_NAME,
) -> onnx.ModelProto:
    """The same weights under configurable tensor names.

    The renamed variant exists to prove that a conforming graph is fed by the name its manifest declares rather than
    by the literal ``input``: identical weights mean the two models must score identically, so a difference can only
    come from the plumbing.
    """
    weights = helper.make_tensor("weights", TensorProto.FLOAT, [FEATURE_COUNT, 1], WEIGHTS)
    bias = helper.make_tensor("bias", TensorProto.FLOAT, [1], [BIAS])
    graph = helper.make_graph(
        [
            helper.make_node("MatMul", [input_name, "weights"], ["weighted"]),
            helper.make_node("Add", ["weighted", "bias"], ["logit"]),
            helper.make_node("Sigmoid", ["logit"], [output_name]),
        ],
        graph_name,
        [helper.make_tensor_value_info(input_name, TensorProto.FLOAT, ["batch", FEATURE_COUNT])],
        [helper.make_tensor_value_info(output_name, TensorProto.FLOAT, ["batch", 1])],
        [weights, bias],
    )
    model = helper.make_model(graph, opset_imports=[helper.make_opsetid("", 13)], ir_version=8)
    onnx.checker.check_model(model, full_check=True)
    return model


def manifest(
    digest: str,
    model_id: str,
    version: str,
    role: str | None,
    input_name: str = INPUT_NAME,
    output_name: str = OUTPUT_NAME,
) -> dict:
    common = {
        "manifestVersion": version,
        "modelId": model_id,
        "modelSha256": digest,
        "featureSchema": SCHEMA,
        "featureCount": FEATURE_COUNT,
        "engineCompatibility": ENGINE_COMPATIBILITY,
        "calibration": {"temperature": 1.0},
        "provenance": {
            "generator": "jvm/src/test/resources/generate_model_contract_fixtures.py",
            "purpose": "engine #78 model-contract test fixture",
            "trained": "false",
        },
    }
    if version == "1.0.0":
        # The version the evaluation service and the kcp-13 serving contract emit: no role, no
        # perspective, no tensor names, and an evaluation profile the engine records but never uses.
        return {**common, "evaluationProfile": "standard-kcp"}
    return {
        **common,
        "modelRole": role,
        "inputName": input_name,
        "outputName": output_name,
        "perspective": "side-to-move",
    }


def write_json(path: Path, payload: dict) -> None:
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {path.name}")


def main() -> None:
    base = Path(__file__).parent
    model_path = base / MODEL_FILE
    onnx.save(make_model(), model_path)
    print(f"wrote {model_path.name}")
    digest = hashlib.sha256(model_path.read_bytes()).hexdigest()

    write_json(
        base / "synthetic_kcp13_value_manifest.json",
        manifest(digest, "synthetic-kcp13-value", "1.1.0", "position-value"),
    )
    write_json(
        base / "synthetic_kcp13_value_legacy_manifest.json",
        manifest(digest, "synthetic-kcp13-value-legacy", "1.0.0", None),
    )
    write_json(
        base / "synthetic_kcp13_collapse_manifest.json",
        manifest(digest, "synthetic-kcp13-collapse", "1.1.0", "chance-collapse"),
    )

    renamed_path = base / RENAMED_MODEL_FILE
    onnx.save(
        make_model("synthetic-kcp13-renamed", RENAMED_INPUT_NAME, RENAMED_OUTPUT_NAME),
        renamed_path,
    )
    print(f"wrote {renamed_path.name}")
    write_json(
        base / "synthetic_kcp13_renamed_tensors_manifest.json",
        manifest(
            hashlib.sha256(renamed_path.read_bytes()).hexdigest(),
            "synthetic-kcp13-renamed",
            "1.1.0",
            "position-value",
            RENAMED_INPUT_NAME,
            RENAMED_OUTPUT_NAME,
        ),
    )

    rows = np.asarray([probe["features"] for probe in PROBES], dtype=np.float32)
    session = ort.InferenceSession(str(model_path), providers=["CPUExecutionProvider"])
    (outputs,) = session.run([OUTPUT_NAME], {INPUT_NAME: rows})
    assert outputs.shape == (len(PROBES), 1), outputs.shape
    write_json(
        base / PARITY_FILE,
        {
            "schema": SCHEMA,
            "perspective": "side-to-move",
            "model": MODEL_FILE,
            "modelSha256": digest,
            "generator": "jvm/src/test/resources/generate_model_contract_fixtures.py",
            "runtime": f"onnxruntime {ort.__version__} (Python, CPUExecutionProvider)",
            "featureSource": "dicechess-training tests/fixtures/kcp13/golden-engine-0.12.0.json",
            "columns": [
                "p_diff",
                "n_diff",
                "b_diff",
                "r_diff",
                "q_diff",
                "material_diff",
                "total_material",
                "mobility_diff",
                "king_safety_diff",
                "king_capture_attack",
                "king_capture_danger",
                "queen_capture_attack",
                "queen_capture_danger",
            ],
            "probes": [
                {**probe, "output": float(outputs[index][0])}
                for index, probe in enumerate(PROBES)
            ],
        },
    )


if __name__ == "__main__":
    main()
