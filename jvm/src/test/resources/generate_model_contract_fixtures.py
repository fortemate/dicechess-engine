"""Generate the ONNX model-contract fixtures: a conforming kcp-13 value model, its manifests, and the
Python-side inference outputs the JVM parity test compares against (engine #78).

Unlike the other synthetic fixtures here, this model satisfies the *serving contract* shared with
dicechess-training: one FLOAT input named ``input`` shaped ``[batch, 13]``, one FLOAT output named
``output`` shaped ``[batch, 1]``, and a bounded (sigmoid) output that is a probability rather than an
unbounded regression score. The older fixtures name their output ``variable``, which is exactly the
mismatch ``OnnxModelContract`` exists to reject.

The graph is linear plus a sigmoid, so every expected value can be recomputed by hand:

    p = sigmoid(sum(WEIGHTS[i] * features[i]) + BIAS)

Run with a Python environment that has onnx + onnxruntime + numpy (the dicechess-training venv is one):

    python3 generate_model_contract_fixtures.py
"""

from __future__ import annotations

